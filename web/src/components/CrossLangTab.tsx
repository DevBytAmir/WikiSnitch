import { Link } from "react-router-dom";
import { api } from "../api/client";
import type { AssessmentLabel, CrossLangMatch, CrossLangTarget, CrossLangView, Lang } from "../api/types";
import { formatDate, formatSimilarity, safeWikipediaUrl } from "../lib/format";
import { Async, useApi } from "./Async";
import { Icon } from "./Icon";
import { LangTag, Meter } from "./ui";

export const LANGUAGE_NAME: Record<Lang, string> = { fi: "Finnish", sv: "Swedish", en: "English" };
export const UNCALIBRATED_NOTE = "Match thresholds are not calibrated yet.";

const ASSESSMENT_WORDS: Record<AssessmentLabel, string> = {
  agrees: "The texts agree",
  differs: "The texts differ",
  source_has_more: "This text says more",
  target_has_more: "The other text says more",
  contradicts: "The texts contradict each other",
};

export function CrossLangTab({
  lang,
  pageId,
  paraId,
  asOf,
}: {
  lang: Lang;
  pageId: number;
  paraId: number;
  asOf?: string;
}) {
  const view = useApi(() => api.crosslang(lang, pageId, paraId, asOf), [lang, pageId, paraId, asOf]);
  return <Async state={view}>{(data) => <CrossLangBody data={data} />}</Async>;
}

export function CrossLangBody({ data }: { data: CrossLangView }) {
  if (data.note) return <p className="crosslang-note empty-note">{data.note}</p>;
  const calibrated = data.thresholds.calibrated;
  return (
    <div className="crosslang">
      <p className="crosslang-intro muted small">
        What the other language versions of this topic say. Similarity measures closeness of meaning, not truth.
      </p>
      {!calibrated && <p className="note-box">{UNCALIBRATED_NOTE}</p>}
      {data.targets.map((t) => (
        <TargetSection key={t.lang} t={t} source={data.source.text} calibrated={calibrated} />
      ))}
    </div>
  );
}

function similarityText(x: number): string {
  return `${formatSimilarity(x)} similarity of meaning`;
}

function Similarity({ x }: { x: number }) {
  return (
    <span className="similarity">
      <Meter value={x} />
      <span className="caption">{similarityText(x)}</span>
    </span>
  );
}

function TargetSection({ t, source, calibrated }: { t: CrossLangTarget; source: string; calibrated: boolean }) {
  const language = LANGUAGE_NAME[t.lang];
  const best = t.matches[0];

  let body;
  if (t.verdict === "no_article" || t.article === null) {
    body = <p className="empty-note">There is no {language} article on this topic in the dataset.</p>;
  } else if (t.verdict === "not_found") {
    body = (
      <>
        {calibrated && <span className="verdict-tag verdict-not_found">Not found in the {language} article</span>}
        {best && (
          <>
            {calibrated ? (
              <p className="caption">{`Nearest passage, below the match threshold (${formatSimilarity(best.similarity)})`}</p>
            ) : (
              <p className="caption">{`Nearest passage: ${similarityText(best.similarity)}`}</p>
            )}
            <SideBySide source={source} match={best} t={t} />
          </>
        )}
      </>
    );
  } else {
    body = (
      <>
        <div className="verdict-line">
          {calibrated && (
            <span className={`verdict-tag verdict-${t.verdict}`}>
              {t.verdict === "same_claim" ? "Same claim" : "Related passage"}
            </span>
          )}
          {best && <Similarity x={best.similarity} />}
        </div>
        {best && <SideBySide source={source} match={best} t={t} />}
      </>
    );
  }

  const nd = t.number_differences;
  const showNumbers = nd !== null && (nd.only_in_source.length > 0 || nd.only_in_target.length > 0);

  return (
    <section className="target" aria-label={`${language} article`}>
      <div className="target-head">
        <LangTag lang={t.lang} />
        <h3>{language}</h3>
        {t.article && <span className="target-title">{t.article.title}</span>}
      </div>
      {body}
      {showNumbers && (
        <p className="numbers numbers-differ">
          Numbers differ: here {nd.only_in_source.join(", ") || "none"}; there {nd.only_in_target.join(", ") || "none"}
        </p>
      )}
      {t.assessment && (
        <div className="assessment">
          <p>
            <strong>{ASSESSMENT_WORDS[t.assessment.label]}:</strong> {t.assessment.explanation}
          </p>
          <p className="caption">Generated by {t.assessment.model}; check both texts.</p>
        </div>
      )}
      {t.elsewhere.length > 0 && (
        <div className="elsewhere">
          <p className="caption">Also covered in</p>
          <ul>
            {t.elsewhere.slice(0, 3).map((e) => (
              <li key={`${e.page_id}-${e.para_id}`}>
                <Link to={`/a/${t.lang}/${e.page_id}?p=${e.para_id}`}>{e.title}</Link>{" "}
                <span className="muted">({formatSimilarity(e.similarity)})</span>
                <p className="elsewhere-text">{e.text}</p>
              </li>
            ))}
          </ul>
        </div>
      )}
    </section>
  );
}

function SideBySide({ source, match, t }: { source: string; match: CrossLangMatch; t: CrossLangTarget }) {
  const art = t.article!;
  const wiki = safeWikipediaUrl(art.wikipedia_url);
  return (
    <div className="side-by-side">
      <blockquote className="side side-here">
        <p className="caption">Here</p>
        <p>{source}</p>
      </blockquote>
      <blockquote className="side side-there">
        <p className="caption">
          {art.title}
          {match.section ? ` · ${match.section}` : ""} · text as of {formatDate(art.snapshot)}
        </p>
        <p>{match.text}</p>
        <p className="side-links">
          <Link to={`/a/${t.lang}/${art.page_id}?p=${match.para_id}`}>Open this paragraph</Link>
          {wiki && (
            <>
              {" · "}
              <a href={wiki} target="_blank" rel="noreferrer">
                On Wikipedia <Icon name="arrow-up-right" size={11} />
              </a>
            </>
          )}
        </p>
      </blockquote>
    </div>
  );
}
