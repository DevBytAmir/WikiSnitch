import { render, screen, within } from "@testing-library/react";
import { MemoryRouter } from "react-router-dom";
import { expect, test } from "vitest";
import type { CrossLangTarget, CrossLangView } from "../api/types";
import fixture from "../../fixtures/crosslang-fi-9001-1.json";
import short from "../../fixtures/crosslang-fi-9002-1.json";
import { CrossLangBody, UNCALIBRATED_NOTE } from "./CrossLangTab";

const BASE = fixture as CrossLangView;
const CAL = { same_claim: 0.75, related: 0.6, calibrated: true };
const EN = BASE.targets[0]; // same_claim, numbers differ
const SV = BASE.targets[1]; // not_found, nearest S1

function show(targets: CrossLangTarget[], over: Partial<CrossLangView> = {}) {
  render(
    <MemoryRouter>
      <CrossLangBody data={{ ...BASE, thresholds: CAL, ...over, targets }} />
    </MemoryRouter>,
  );
}
const section = (name: string) => screen.getByRole("region", { name: `${name} article` });

test("same_claim shows the tag, similarity, both texts, snapshot and link", () => {
  show([EN]);
  const s = section("English");
  expect(within(s).getByText("Same claim")).toBeInTheDocument();
  expect(within(s).getByText("0.83 similarity of meaning")).toBeInTheDocument();
  expect(within(s).getByText(BASE.source.text)).toBeInTheDocument();
  expect(within(s).getByText(EN.matches[0].text)).toBeInTheDocument();
  expect(s).toHaveTextContent("text as of 1 Aug 2025");
  expect(within(s).getByRole("link", { name: "Open this paragraph" })).toHaveAttribute("href", "/a/en/8001?p=1");
  expect(s).not.toHaveTextContent("%");
});

test("related shows the related tag", () => {
  show([{ ...EN, verdict: "related" }]);
  expect(within(section("English")).getByText("Related passage")).toBeInTheDocument();
});

test("not_found shows the nearest passage below the threshold", () => {
  show([SV]);
  const s = section("Swedish");
  expect(within(s).getByText("Not found in the Swedish article")).toBeInTheDocument();
  expect(within(s).getByText("Nearest passage, below the match threshold (0.17)")).toBeInTheDocument();
  expect(within(s).getByText(SV.matches[0].text)).toBeInTheDocument();
});

test("no_article sentence", () => {
  show([{ ...SV, verdict: "no_article", article: null, matches: [] }]);
  expect(screen.getByText("There is no Swedish article on this topic in the dataset.")).toBeInTheDocument();
});

test("number differences line", () => {
  show([EN]);
  expect(section("English")).toHaveTextContent("Numbers differ: here 70000; there 25000");
});

test("assessment with its caption", () => {
  show([{ ...EN, assessment: { label: "differs", explanation: "The figures differ.", model: "test-model" } }]);
  const s = section("English");
  expect(s).toHaveTextContent("The texts differ: The figures differ.");
  expect(within(s).getByText("Generated by test-model; check both texts.")).toBeInTheDocument();
});

test("elsewhere lists up to three linked passages", () => {
  const e = (n: number) => ({ page_id: 500 + n, title: `Other ${n}`, para_id: n, text: `Passage ${n}`, similarity: 0.7 });
  show([{ ...SV, elsewhere: [e(1), e(2), e(3), e(4)] }]);
  const s = section("Swedish");
  expect(within(s).getByText("Also covered in")).toBeInTheDocument();
  expect(within(s).getAllByRole("link", { name: /^Other / })).toHaveLength(3);
  expect(within(s).getByRole("link", { name: "Other 1" })).toHaveAttribute("href", "/a/sv/501?p=1");
});

test("uncalibrated thresholds show similarity without verdict wording", () => {
  show([EN, SV], { thresholds: { ...CAL, calibrated: false } });
  expect(screen.getByText(UNCALIBRATED_NOTE)).toBeInTheDocument();
  expect(screen.queryByText("Same claim")).toBeNull();
  expect(screen.queryByText(/Not found in the/)).toBeNull();
  expect(screen.getByText("0.83 similarity of meaning")).toBeInTheDocument();
});

test("top-level note replaces the sections", () => {
  render(
    <MemoryRouter>
      <CrossLangBody data={short as CrossLangView} />
    </MemoryRouter>,
  );
  expect(screen.getByText("This paragraph is too short to compare.")).toBeInTheDocument();
  expect(screen.queryByRole("region")).toBeNull();
});
